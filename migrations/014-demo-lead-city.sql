-- ۰۱۴ — شهر و شعبه در درخواست دمو
--
-- فرم دمو در سایت دو سؤال مهم می‌پرسد:
--
--   «شهر و تعداد شعبه»            → id="f-city"
--   «بزرگ‌ترین دردسر امروزتان؟»   → id="f-msg"
--
-- و هیچ‌کدام هرگز به سرور نمی‌رسید. جاوااسکریپت فرم دنبال `f-note` و
-- `f-email` می‌گشت که اصلاً در صفحه وجود ندارند، پس همیشه رشتهٔ خالی
-- می‌فرستاد. یعنی ارزشمندترین بخش هر سرنخ — اینکه طرف دقیقاً چه دردی
-- دارد — بی‌صدا دور ریخته می‌شد، و فروش با یک نام و شماره تنها می‌ماند.
--
-- سمت جاوااسکریپت درست شد (note از f-msg، city از f-city). `note` از
-- قبل ستون داشت؛ `city` نداشت.
--
-- چرا ستون جدا و نه چسباندن به note: سوپرادمین بعداً می‌خواهد بداند
-- کدام شهرها بیشتر درخواست می‌دهند. متنی که داخل یادداشت آزاد قاطی
-- شده باشد، شمردنی نیست.

ALTER TABLE demo_lead
  ADD COLUMN city VARCHAR(120) NULL AFTER institute;

